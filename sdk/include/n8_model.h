/* The model broker's client (`docs/sdk-guide/03-async-model-broker-api.md`): an app with
 * no direct accelerator grant asks pVM #1 (cortex-mvp) for a model turn through the gate.
 *
 * Asynchronous, as every pVM-to-pVM message is: n8_model_request queues the request and returns;
 * the answer arrives later in the app's own n8_on_message with op == N8_MODEL_REPLY, the reply in
 * the inbox. Decode it with n8_model_parse. One request in flight at a time.
 *
 * The app's manifest entry needs "allowed_ipc": [1]; without the bit the request contains the app. */
#ifndef N8_MODEL_H
#define N8_MODEL_H

#include <stdint.h>

#include "n8_ops.h"

#define N8_MODEL_BROKER 1 /* pVM #1 */
#define N8_MODEL_MAX_PROMPT 256
#define N8_MODEL_MAX_BYTES 64
#define N8_MODEL_REPLY ((int32_t)(N8_OP_MODEL_TURN | 0x80000000u))

#define N8_MODEL_E_BUSY -1  /* a request is already in flight */
#define N8_MODEL_E_RATE -2  /* "ERR broker rate": under 500 ms since this app's last turn */
#define N8_MODEL_E_SIZE -3  /* the prompt is over 256 bytes ("ERR broker size" from the broker) */
#define N8_MODEL_E_MODEL -4 /* "ERR no-model" */
#define N8_MODEL_E_REPLY -5 /* any other answer: "ERR broker op", a malformed reply */

/* Queue a turn: the prompt's n bytes, then up to max_bytes generated (clamped to 1..64).
 * 0 when queued; N8_MODEL_E_BUSY or N8_MODEL_E_SIZE; or the gate's negative status. */
int32_t n8_model_request(const char *prompt, int32_t n, int32_t max_bytes);

/* Decode the broker's reply (len bytes at inbox): the generated bytes into out (NUL-terminated,
 * at most cap - 1), their count; or a negative N8_MODEL_E_*. Clears the in-flight flag. */
int32_t n8_model_parse(const uint8_t *inbox, int32_t len, char *out, int32_t cap);

/* 1 while a request is in flight */
int32_t n8_model_pending(void);

#endif
